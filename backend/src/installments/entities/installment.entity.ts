import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Wallet } from '../../wallets/entities/wallet.entity';

export enum InstallmentStatus {
  PENDING = 'PENDING',
  OVERDUE = 'OVERDUE',
  PAID = 'PAID',
  // The credit purchase this installment was generated from was refunded
  // before it was paid off — nothing is owed any more (see
  // InstallmentsService.cancelForPurchase).
  CANCELED = 'CANCELED',
}

// One scheduled repayment of a single credit-funded purchase back to the
// credit wallet's repository — see InstallmentsService (generation the
// moment the purchase settles, plus the daily due-date check and overdue
// sweep)
// and TransactionsService.payInstallment (repayment, via the same IPG
// purchase flow as any other purchase, paid into the repository's real
// balance).
@Entity('installments')
export class Installment {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Index()
  @Column({ type: 'uuid' })
  walletId: string;

  @ManyToOne(() => Wallet)
  @JoinColumn({ name: 'walletId' })
  wallet: Wallet;

  // The credit-funded PURCHASE this installment's plan was generated from
  // (see InstallmentsService.createForPurchase) — shared by every row of
  // the same plan (sequenceNumber 1..installmentCount), and how a repeat
  // settle call tells the plan already exists. Null on rows generated by
  // the older monthly-billing-period model.
  @Index()
  @Column({ type: 'uuid', nullable: true })
  purchaseTransactionId: string | null;

  // The day the plan was created on (the purchase date) — both ends are the
  // same day for a per-purchase plan. Older monthly-period rows hold the
  // one-month window [periodStart, periodEnd) they were summed over.
  @Column({ type: 'date' })
  periodStart: string;

  @Index()
  @Column({ type: 'date' })
  periodEnd: string;

  // 1-based position within the credit line's WalletType.installmentCount
  // schedule.
  @Column({ type: 'smallint' })
  sequenceNumber: number;

  // Principal share (virtualAmount / installmentCount, remainder folded into
  // the last installment) plus the type's feePercent, in minor units. Grows
  // by penaltyPercentPerDay for every day it stays unpaid past deadlineDate.
  @Column({ type: 'bigint' })
  amount: string;

  // The principal share alone, fixed at generation time before feePercent is
  // folded into `amount` — the fee/penalty percentage base, so daily penalty
  // accrual is always a percentage of this fixed principal rather than of
  // the ever-growing `amount` (which would compound).
  @Column({ type: 'bigint' })
  principalAmount: string;

  // The fee share alone (feePercent of principalAmount), also fixed at
  // generation time — kept separate from principalAmount so a repayment can
  // recover exactly how much of `amount` is principal vs. fee vs. penalty
  // (penalty = amount - principalAmount - feeAmount, the only one of the
  // three that keeps growing after generation) and route each slice to its
  // own repository — see InstallmentsService.computeRepaymentSplit.
  @Column({ type: 'bigint' })
  feeAmount: string;

  @Column({ type: 'boolean', default: false })
  penaltyApplied: boolean;

  // How many days' worth of penaltyPercentPerDay have already been folded
  // into `amount` — lets applyOverduePenalties top up exactly the owed
  // difference each run instead of double-applying, regardless of how many
  // days have passed since the last sweep.
  @Column({ type: 'smallint', default: 0 })
  penaltyDaysApplied: number;

  // The day this installment falls due — monthly from the purchase, on the
  // type's installmentDate day of month when one is set.
  @Column({ type: 'date' })
  dueDate: string;

  // When the daily sweep checked this installment on (or after) its due
  // date — see InstallmentsService.checkDueInstallments. Null until then.
  @Column({ type: 'timestamptz', nullable: true })
  dueCheckedAt: Date | null;

  // The day by which it must be paid before it's marked OVERDUE
  // (WalletType.paymentDeadlineDate) and the wallet gets blocked.
  @Column({ type: 'date' })
  deadlineDate: string;

  @Column({
    type: 'enum',
    enum: InstallmentStatus,
    enumName: 'installments_status_enum',
    default: InstallmentStatus.PENDING,
  })
  status: InstallmentStatus;

  @Column({ type: 'timestamptz', nullable: true })
  paidAt: Date | null;

  @Column({ type: 'uuid', nullable: true })
  paymentTransactionId: string | null;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt: Date;

  @UpdateDateColumn({ type: 'timestamptz' })
  updatedAt: Date;
}
